export function getTranslation(locale: StudioLocale, key: string): string {
  const dict = TRANSLATIONS[locale] || TRANSLATIONS.en;
  if (dict[key]) return dict[key];
  if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
  return key;
}

export const STORAGE_KEY_LANG = "plp_studio_lang";

export function getSavedLocale(): StudioLocale {
  if (typeof window === "undefined") return "km";
  try {
    const saved = localStorage.getItem(STORAGE_KEY_LANG) as StudioLocale | null;
    if (saved && SUPPORTED_LOCALES.some((l) => l.code === saved)) {
      return saved;
    }
  } catch {}
  return "km";
}

export function saveLocale(locale: StudioLocale): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(STORAGE_KEY_LANG, locale);
    window.dispatchEvent(new CustomEvent("plp_studio_lang_change", { detail: locale }));
  } catch {}
}
